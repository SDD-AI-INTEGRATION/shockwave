-- Governance, finance, early warning, capacity, and closure features.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS contract_number text NOT NULL DEFAULT '';
ALTER TABLE projects ADD COLUMN IF NOT EXISTS contract_value numeric(18,2) NOT NULL DEFAULT 0 CHECK(contract_value>=0);
ALTER TABLE projects ADD COLUMN IF NOT EXISTS closed_at timestamptz;
ALTER TABLE users ADD COLUMN IF NOT EXISTS capacity integer NOT NULL DEFAULT 3 CHECK(capacity BETWEEN 1 AND 50);

-- Multi-level approvals. Step 1 = project manager, step 2 = PMO administrator.
CREATE TABLE IF NOT EXISTS approvals (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES projects(id),
 kind text NOT NULL CHECK(kind IN ('baseline','weekly_report','document','change_request','closure')),
 resource_id text NOT NULL,
 title text NOT NULL,
 snapshot jsonb NOT NULL DEFAULT '{}',
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected','cancelled')),
 current_step integer NOT NULL DEFAULT 1,
 requested_by uuid NOT NULL REFERENCES users(id),
 requested_at timestamptz NOT NULL DEFAULT now(),
 decided_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS approvals_one_pending ON approvals(project_id,kind,resource_id) WHERE status='pending';
CREATE INDEX IF NOT EXISTS approvals_project ON approvals(project_id,requested_at DESC);
CREATE TABLE IF NOT EXISTS approval_steps (
 approval_id uuid NOT NULL REFERENCES approvals(id) ON DELETE CASCADE,
 step integer NOT NULL,
 approver_role text NOT NULL CHECK(approver_role IN ('project_manager','pmo')),
 decision text NOT NULL DEFAULT 'pending' CHECK(decision IN ('pending','approved','rejected','skipped')),
 decided_by uuid REFERENCES users(id),
 decided_at timestamptz,
 note text NOT NULL DEFAULT '',
 PRIMARY KEY(approval_id,step)
);

-- Change requests and baseline history.
CREATE TABLE IF NOT EXISTS change_requests (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES projects(id),
 number text NOT NULL,
 title text NOT NULL,
 type text NOT NULL CHECK(type IN ('scope','timeline','cost','pic')),
 description text NOT NULL DEFAULT '',
 reason text NOT NULL,
 impact text NOT NULL DEFAULT '',
 changes jsonb NOT NULL DEFAULT '{}',
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','pending','approved','rejected','cancelled')),
 created_by uuid NOT NULL REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 applied_at timestamptz,
 UNIQUE(project_id,number)
);
CREATE TABLE IF NOT EXISTS baseline_history (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES projects(id),
 version integer NOT NULL,
 phases jsonb NOT NULL,
 reason text NOT NULL DEFAULT '',
 change_request_id uuid REFERENCES change_requests(id),
 created_by uuid NOT NULL REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(project_id,version)
);

-- Central action items from meetings, MOM, and manual entry.
CREATE TABLE IF NOT EXISTS action_items (
 id uuid PRIMARY KEY,
 project_id uuid NOT NULL REFERENCES projects(id),
 source text NOT NULL CHECK(source IN ('meeting','mom','manual')),
 source_id text NOT NULL DEFAULT '',
 source_label text NOT NULL DEFAULT '',
 text text NOT NULL,
 pic text NOT NULL,
 pic_user_id uuid REFERENCES users(id),
 due date NOT NULL,
 status text NOT NULL DEFAULT 'not_started' CHECK(status IN ('not_started','in_progress','pending','done','cancelled')),
 evidence text NOT NULL DEFAULT '',
 evidence_document_id uuid REFERENCES documents(id),
 completed_by uuid REFERENCES users(id),
 completed_at timestamptz,
 created_by uuid NOT NULL REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS action_items_project ON action_items(project_id,status,due);

-- Billing milestones (termin), invoices, payments.
CREATE TABLE IF NOT EXISTS billing_milestones (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES projects(id),
 name text NOT NULL,
 percentage numeric(6,2) NOT NULL DEFAULT 0 CHECK(percentage BETWEEN 0 AND 100),
 amount numeric(18,2) NOT NULL DEFAULT 0 CHECK(amount>=0),
 due_date date,
 wbs_task_id uuid,
 requires_bast boolean NOT NULL DEFAULT true,
 bast_document_id uuid REFERENCES documents(id),
 invoice_number text NOT NULL DEFAULT '',
 invoice_date date,
 invoice_document_id uuid REFERENCES documents(id),
 paid_amount numeric(18,2) NOT NULL DEFAULT 0 CHECK(paid_amount>=0),
 paid_date date,
 notes text NOT NULL DEFAULT '',
 sort_order integer NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS billing_project ON billing_milestones(project_id,sort_order);

-- In-app notifications generated by the early-warning job and approvals.
CREATE TABLE IF NOT EXISTS notifications (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 project_id uuid REFERENCES projects(id),
 level text NOT NULL CHECK(level IN ('red','amber','info')),
 title text NOT NULL,
 body text NOT NULL DEFAULT '',
 dedupe_key text NOT NULL,
 read_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(user_id,dedupe_key)
);
CREATE INDEX IF NOT EXISTS notifications_user ON notifications(user_id,read_at,created_at DESC);

-- Project closure and lessons learned.
CREATE TABLE IF NOT EXISTS project_closures (
 project_id uuid PRIMARY KEY REFERENCES projects(id),
 checklist jsonb NOT NULL DEFAULT '[]',
 handover jsonb NOT NULL DEFAULT '{}',
 lessons jsonb NOT NULL DEFAULT '[]',
 summary text NOT NULL DEFAULT '',
 status text NOT NULL DEFAULT 'open' CHECK(status IN ('open','pending','closed')),
 version integer NOT NULL DEFAULT 1,
 updated_by uuid REFERENCES users(id),
 updated_at timestamptz NOT NULL DEFAULT now(),
 search_vector tsvector GENERATED ALWAYS AS (to_tsvector('simple',coalesce(summary,'')||' '||coalesce(lessons::text,''))) STORED
);
CREATE INDEX IF NOT EXISTS closures_search ON project_closures USING gin(search_vector);
